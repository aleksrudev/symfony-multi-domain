<?php

declare(strict_types=1);

namespace Tests\Integration;

use App\Shared\Infrastructure\Messaging\IntegrationEventEnvelope;
use App\Shared\Infrastructure\Messaging\IntegrationEventPublisher;
use DAMA\DoctrineTestBundle\PHPUnit\SkipDatabaseRollback;
use Doctrine\DBAL\Connection;
use Doctrine\DBAL\DriverManager;
use Doctrine\ORM\EntityManagerInterface;
use PHPUnit\Framework\Attributes\PreserveGlobalState;
use PHPUnit\Framework\Attributes\RunInSeparateProcess;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Messenger\Transport\Serialization\PhpSerializer;
use Tests\Fixtures\Modules\Alpha\Presentation\Contracts\Dto\ProbeItem;
use Tests\Fixtures\Modules\Alpha\Presentation\Contracts\Event\ProbePublishedEvent;
use Tests\Fixtures\PostgresIntegrationEventsKernel;

final class PostgresIntegrationEventTest extends TestCase
{
    #[RunInSeparateProcess]
    #[PreserveGlobalState(false)]
    #[SkipDatabaseRollback]
    public function testSourceAndAllSubscriberDeliveriesCommitOrRollbackTogether(): void
    {
        if (!getenv('OUTBOX_TEST_DATABASE_URL')) {
            self::markTestSkipped('Dedicated PostgreSQL test database is not configured.');
        }
        $kernel = new PostgresIntegrationEventsKernel('test', true);
        $db = $observer = null;
        $messageIds = [];
        $value = random_int(100000, 1000000000);
        try {
            $kernel->boot();
            $container = $kernel->getContainer()->get('test.service_container');
            $db = $container->get(EntityManagerInterface::class)->getConnection();
            $guard = require dirname(__DIR__, 2).'/tools/test-database-guard.php';
            $guard('test', true, $db->getParams());
            $db->executeStatement('CREATE SCHEMA IF NOT EXISTS alpha');
            $db->executeStatement('CREATE TABLE IF NOT EXISTS alpha.integration_probe (value INTEGER NOT NULL)');
            $db->executeStatement('CREATE TABLE IF NOT EXISTS public.messenger_messages (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, body TEXT NOT NULL, headers TEXT NOT NULL, queue_name VARCHAR(190) NOT NULL, created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL, available_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL, delivered_at TIMESTAMP(0) WITHOUT TIME ZONE DEFAULT NULL)');
            $observer = DriverManager::getConnection($db->getParams());
            $publisher = $container->get('test.integration_event_publisher');
            self::assertInstanceOf(IntegrationEventPublisher::class, $publisher);

            $db->beginTransaction();
            $db->insert('alpha.integration_probe', ['value' => $value]);
            $metadata = $publisher->publish(new ProbePublishedEvent($value, [new ProbeItem('item-1', 3)]), new \DateTimeImmutable('2026-10-22T09:30:00.123456Z'));
            $messageIds = $this->messageIds($db, $metadata->eventId);
            self::assertCount(2, $messageIds);
            self::assertSame([], $this->messageIds($observer, $metadata->eventId));
            self::assertSame(0, $observer->fetchOne('SELECT COUNT(*) FROM alpha.integration_probe WHERE value = ?', [$value]));
            $db->commit();
            self::assertSame($messageIds, $this->messageIds($observer, $metadata->eventId));
            self::assertSame(1, $observer->fetchOne('SELECT COUNT(*) FROM alpha.integration_probe WHERE value = ?', [$value]));

            $db->beginTransaction();
            $db->insert('alpha.integration_probe', ['value' => $value + 1]);
            $rolledBack = $publisher->publish(new ProbePublishedEvent($value + 1, []), new \DateTimeImmutable());
            self::assertCount(2, $this->messageIds($db, $rolledBack->eventId));
            $db->rollBack();
            self::assertSame([], $this->messageIds($observer, $rolledBack->eventId));
            self::assertSame(0, $observer->fetchOne('SELECT COUNT(*) FROM alpha.integration_probe WHERE value = ?', [$value + 1]));
        } finally {
            if (null !== $db && $db->isTransactionActive()) {
                $db->rollBack();
            }
            if (null !== $observer) {
                foreach ($messageIds as $id) {
                    $observer->executeStatement('DELETE FROM public.messenger_messages WHERE id = ?', [$id]);
                }
                $observer->executeStatement('DELETE FROM alpha.integration_probe WHERE value IN (?, ?)', [$value, $value + 1]);
                $observer->close();
            }
            $kernel->shutdown();
        }
    }

    /** @return list<string> */
    private function messageIds(Connection $db, string $eventId): array
    {
        $ids = [];
        $serializer = new PhpSerializer();
        foreach ($db->fetchAllAssociative("SELECT id, body, headers FROM public.messenger_messages WHERE queue_name = 'outbox' ORDER BY id") as $row) {
            $message = $serializer->decode(['body' => (string) $row['body'], 'headers' => json_decode((string) $row['headers'], true, flags: JSON_THROW_ON_ERROR)])->getMessage();
            if ($message instanceof IntegrationEventEnvelope && $message->metadata->eventId === $eventId) {
                $ids[] = (string) $row['id'];
            }
        }

        return $ids;
    }
}
