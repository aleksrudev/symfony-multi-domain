<?php

declare(strict_types=1);

namespace Tests\Integration;

use App\Shared\Application\Bus\Command\CommandBusInterface;
use DAMA\DoctrineTestBundle\PHPUnit\SkipDatabaseRollback;
use Doctrine\DBAL\DriverManager;
use Doctrine\ORM\EntityManagerInterface;
use PHPUnit\Framework\Attributes\PreserveGlobalState;
use PHPUnit\Framework\Attributes\RunInSeparateProcess;
use PHPUnit\Framework\TestCase;
use Tests\Fixtures\Modules\Alpha\Application\ProbeCommand;
use Tests\Fixtures\Modules\Alpha\Domain\ProbeFailure;
use Tests\Fixtures\PostgresModuleKernel;

final class PostgresOutboxTest extends TestCase
{
    #[RunInSeparateProcess]
    #[PreserveGlobalState(false)]
    #[SkipDatabaseRollback]
    public function testCommandAndOutboxShareOneTransactionAcrossSchemas(): void
    {
        if (!getenv('OUTBOX_TEST_DATABASE_URL')) {
            self::markTestSkipped('Dedicated PostgreSQL test database is not configured.');
        }

        $kernel = new PostgresModuleKernel('test', true);
        $observer = null;
        $messageId = null;
        $value = random_int(100000, 1000000000);
        try {
            $kernel->boot();
            $container = $kernel->getContainer()->get('test.service_container');
            $db = $container->get(EntityManagerInterface::class)->getConnection();
            $guard = require dirname(__DIR__, 2).'/tools/test-database-guard.php';
            $guard('test', true, $db->getParams());
            $db->executeStatement('CREATE SCHEMA IF NOT EXISTS alpha');
            $db->executeStatement('CREATE TABLE IF NOT EXISTS alpha.txn_probe (value INTEGER NOT NULL)');
            $db->executeStatement('CREATE TABLE IF NOT EXISTS public.messenger_messages (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, body TEXT NOT NULL, headers TEXT NOT NULL, queue_name VARCHAR(190) NOT NULL, created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL, available_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL, delivered_at TIMESTAMP(0) WITHOUT TIME ZONE DEFAULT NULL)');
            $db->executeStatement('SET search_path TO alpha, public');
            $observer = DriverManager::getConnection($db->getParams());
            $bus = $container->get(CommandBusInterface::class);

            $bus->dispatch(new ProbeCommand(value: $value, publish: true));
            $messageId = $db->fetchOne("SELECT id FROM public.messenger_messages WHERE queue_name = 'outbox' ORDER BY id DESC LIMIT 1");
            self::assertNotFalse($messageId);
            self::assertSame(1, $observer->fetchOne('SELECT COUNT(*) FROM alpha.txn_probe WHERE value = ?', [$value]));
            self::assertSame(1, $observer->fetchOne("SELECT COUNT(*) FROM public.messenger_messages WHERE id = ? AND queue_name = 'outbox'", [$messageId]));
            $messageCount = $observer->fetchOne("SELECT COUNT(*) FROM public.messenger_messages WHERE queue_name = 'outbox'");

            try {
                $bus->dispatch(new ProbeCommand(value: $value + 1, fail: true, publish: true));
                self::fail('Expected rollback after publishing.');
            } catch (ProbeFailure) {
                self::assertSame(0, $observer->fetchOne('SELECT COUNT(*) FROM alpha.txn_probe WHERE value = ?', [$value + 1]));
                self::assertSame($messageCount, $observer->fetchOne("SELECT COUNT(*) FROM public.messenger_messages WHERE queue_name = 'outbox'"));
            }
        } finally {
            if (null !== $observer) {
                if (null !== $messageId) {
                    $observer->executeStatement('DELETE FROM public.messenger_messages WHERE id = ?', [$messageId]);
                }
                $observer->executeStatement('DELETE FROM alpha.txn_probe WHERE value IN (?, ?)', [$value, $value + 1]);
                $observer->close();
            }
            $kernel->shutdown();
        }
    }
}
